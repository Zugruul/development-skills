#!/usr/bin/env bash
# section-lint.sh -- sourced by run-tests.sh; do not run standalone.
# Static contracts of the old orchestration workflow: frontmatter, the orchestrator role,
# the report format, the code review flow. It uses the herdr plugin's skills by name and
# carries its own scripts; it never reaches into another plugin's folder.
declare -F check >/dev/null 2>&1 || { echo "section files are sourced by run-tests.sh; run: bash plugins/herdr-simple-orchestrate/tests/run-tests.sh" >&2; exit 2; }
echo "== lint: frontmatter / orchestrator role =="

for skill in orchestrate orchestrate-code-reviews; do
    f="$PLUGIN/skills/$skill/SKILL.md"
    head="$(sed -n '2,/^---$/p' "$f" 2>/dev/null)"
    check "$skill: frontmatter name matches its directory" "name: $skill" "$head"
    check "$skill: has a description" "description: " "$head"
    desc="$(grep '^description: ' <<<"$head")"
    check_absent "$skill: description has no angle brackets (Codex rejects them)" "<" "$desc"
    check_absent "$skill: description has no closing angle brackets" ">" "$desc"
    check "$skill: checks it is inside Herdr first" 'bash "../../scripts/check.sh"' "$(cat "$f")"
done
check_rc "every skill directory is covered above" 2 "$(find "$PLUGIN/skills" -name SKILL.md | wc -l | tr -d ' ')"
while IFS= read -r ref; do
    ok=0; [[ -f "$PLUGIN/${ref#../}" || -f "$PLUGIN/${ref#../../}" ]] || ok=1
    check_rc "skills and references name an existing script: $ref" 0 "$ok"
done < <(grep -rhoE '(\.\./)+scripts/[a-z/-]+\.sh' "$PLUGIN/skills" "$PLUGIN/references" | sort -u)
py="$(find "$PLUGIN" -name '*.py' | sed "s#^$PLUGIN/##")"
check_rc "no Python files in the plugin" 0 "${#py}"
stale="$(grep -rnoE 'herdr_ctl|\.\./(worktree|agent|prompt|listen|status)/SKILL\.md' "$PLUGIN" --exclude-dir=tests || true)"
check_rc "no path into the herdr plugin's folder and no herdr_ctl.py" 0 "${#stale}"
[[ -n "$stale" ]] && echo "     $stale"
orch="$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"
for dep in worktree agent prompt listen status; do
    check "orchestrate: loads the herdr $dep skill" "the \`herdr:$dep\` skill" "$orch"
done
check "orchestrate: the on-demand report decides its case from the conversation" "Decide from this conversation only" "$orch"
check "orchestrate: a name is a hint, not proof" "is a hint that you held the role, never proof" "$orch"
check "orchestrate: unknown falls back to the plain list and says so" "do not guess. Use the plain case and say so" "$orch"
check "orchestrate: a lost earlier report is said, not reconstructed" "Since last report: unknown (the earlier report is no longer in my context)" "$orch"
check "orchestrate: the lists come from mine.sh" 'bash "../../scripts/mine.sh"' "$orch"

echo "== lint: orchestrator report =="
rp="$(cat "$PLUGIN/references/report.md" 2>/dev/null)"
check "report: one reference file holds the format" "# Orchestrator report" "$rp"
for part in "Since last report:" "**🔴 NEEDS YOU (1)**" "**🟡 WORKING (1)**" "**🟢 DONE (1)**" "verified:" "claimed:" "asks:" "prs:"; do
    check "report: the template has '$part'" "$part" "$rp"
done
check "report: sections keep their order" "\`NEEDS YOU\`, \`WORKING\`, \`DONE\`" "$rp"
check "report: section dots" "\`🔴 NEEDS YOU (n)\`, \`🟡 WORKING (n)\`, \`🟢 DONE (n)\`" "$rp"
check "report: empty sections are left out" "Leave out a section that has no agents" "$rp"
check "report: nothing changed is said" "Since last report: nothing changed" "$rp"
check "report: the first report has no change line" "Leave the line out of your first report" "$rp"
check "report: markdown, no table" "No table" "$rp"
check "report: never inside a code fence" "Never wrap the report in a code fence" "$rp"
check "report: prs is a block, one line per pull request" "  - prs:
      ⚪ #2795 draft   https://github.com/<owner>/<repo>/pull/2795
      🔵 #2801 open    https://github.com/<owner>/<repo>/pull/2801
      🟣 #2807 merged  https://github.com/<owner>/<repo>/pull/2807
      🔴 #2811 closed  https://github.com/<owner>/<repo>/pull/2811" "$rp"
check "report: claimed starts with the warning mark" "  - claimed: ⚠ 103 + 28 tests pass" "$rp"
check "report: verified has no marker" "\`verified:\` has no marker" "$rp"
check "report: the pull request dots are fixed" "\`⚪ draft\`, \`🔵 open\`, \`🟣 merged\`, \`🔴 closed\`" "$rp"
check "report: green only means DONE" "Green means DONE and nothing else: an open pull request is blue." "$rp"
check_rc "report: no green dot on a pull request line" 0 "$(grep -c '🟢 #' "$PLUGIN/references/report.md" || true)"
check "report: never color alone" "**Never color alone.**" "$rp"
check "report: no other emoji" "These are the only emoji allowed anywhere in the report" "$rp"
check "report: idle, unknown and gone get the black dot" "\`⚫\` is used for nothing else" "$rp"
for line in "⚫ idle:" "⚫ state: unknown" "⚫ gone:"; do
    check "report: the table marks '$line'" "$line" "$rp"
done
# The example block uses only the allowed marks.
# shellcheck disable=SC2016  # literal backticks: a sed address for the fenced block
check_rc "report: no emoji outside the fixed set in the example" 0 "$(sed -n '/^```markdown/,/^```$/p' "$PLUGIN/references/report.md" | jq -Rrs '[explode[] | select(. > 8192) | [.] | implode | select(IN("🔴","🟡","🟢","🔵","⚪","🟣","⚠","⚫") | not)] | length')"
check "report: one pull request uses the same block" "An agent with one pull request uses the same block" "$rp"
check "report: a direct merge is a row of the prs block" "      ⚪ #2795   draft   https://github.com/<owner>/<repo>/pull/2795
      🟣 direct  merged  main @ 4e843cc" "$rp"
check "report: the direct row comes from git, not from the agent" "**Never write this row from what the agent says or from memory.**" "$rp"
check "report: merged means the remote's main branch" "**\`merged\` means on the remote's main branch**" "$rp"
check "report: local-only work is not purple" "\`⚪ direct  local   main @ <commit>\`" "$rp"
check "report: a squash or cherry-pick is recognised" "(same content)" "$rp"
check "report: earlier states get no row" "**States before that get no row.**" "$rp"
check "report: an unconfirmed landing is a claim" "there is no row; the agent's statement goes under \`claimed:\`" "$rp"
check "report: no double row for a merged pull request" "Do not add a \`direct\` row for the same work." "$rp"
check "report: the color table has the direct marks" "| 🟣 ⚪ | start of a \`direct\` line |" "$rp"
check "orchestrate: the report includes direct rows" "a \`direct\` row from \`landed\`" "$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"
check "report: no pull requests, no prs line" "An agent with none has no \`prs:\` line" "$rp"
check "report: pull requests in opening order" "in the order they were opened" "$rp"
check "report: the four pull request states" "\`draft\`, \`open\`, \`merged\`, \`closed\`" "$rp"
check "report: the URL is full and bare" "written in full and bare, with no Markdown link syntax" "$rp"
check "report: URLs are aligned" "so the URLs start in the same column" "$rp"
check "report: no invented URL" "never guess an address" "$rp"
check "report: clicking depends on the terminal" "depends on the terminal and on Herdr" "$rp"
check "report: the observed result under default mouse capture" "a click does not open the URL" "$rp"
check "report: names the Herdr setting involved" "ui.mouse_capture = true" "$rp"
check "report: other hosts are unverified" "is unverified, and so is every other host" "$rp"
check "report: no claim that URLs open" "Do not tell the user the URLs are clickable. Under Herdr's defaults they are not." "$rp"
check "report: no workaround and no config change" "Do not change the user's Herdr configuration" "$rp"
check_rc "report: no markdown link syntax anywhere in the reference" 0 "$(grep -c '](http' "$PLUGIN/references/report.md" || true)"
check "report: the question is quoted exactly" "quoted exactly" "$rp"
check "report: only for the orchestrator role" "does not apply to an agent that is not orchestrating" "$rp"
check "report: unknown is never done" "An agent Herdr cannot classify is never shown under DONE" "$rp"
check "report: no agent is dropped" "No agent is silently dropped" "$rp"
# shellcheck disable=SC2016  # literal backticks: these are markdown table cells
for state in '`blocked`' '`working`' '`done`' '`idle`' '`unknown`' 'gone'; do
    check "report: places $state" "| $state" "$rp"
done
# The template itself is fenced plain text, not a table.
# shellcheck disable=SC2016  # literal backticks: a sed address for the fenced block
check_rc "report: the example block has no table row" 0 "$(sed -n '/^```markdown/,/^```$/p' "$PLUGIN/references/report.md" | grep -c '^|' || true)"
for skill in orchestrate orchestrate-code-reviews; do
    check "report: $skill points to the reference" "../../references/report.md" "$(cat "$PLUGIN/skills/$skill/SKILL.md")"
done
check "report: the reference covers an on-demand comparison" "or on demand (the \`orchestrate\` skill, section 4)" "$rp"
check "orchestrate: has the on-demand report" "Section 4 is the on-demand form of this report" "$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"
orch_txt="$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"
check "orchestrate: the user's questions about an agent's work are relayed" "**The user's questions about an agent's work go to that agent.**" "$orch_txt"
check "orchestrate: relaying covers questions, errors and bug reports" "asks a question, shows an error, reports a bug" "$orch_txt"
check "orchestrate: no investigating the agent's checkout" "Do not open the agent's checkout to work out the answer yourself" "$orch_txt"
check "orchestrate: read-only work is delegated work too" "This holds for read-only work as much as for edits." "$orch_txt"
check "orchestrate: a mid-turn agent is waited for" "wait until it settles and send then" "$orch_txt"
check "orchestrate: an unowned topic is asked about, not taken" "ask the user who should take it" "$orch_txt"
check "orchestrate: verifying is not investigating" "It is not investigating: diagnosing an error, explaining a design choice or proposing a change" "$orch_txt"
check "orchestrate: the role covers more than editing files" "Delegated work is more than editing files" "$orch_txt"
check "orchestrate: states the role in the conversation" "Say in that reply that you are now the orchestrator" "$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"
check_absent "report: orchestrate no longer describes its own layout" "Keep a roster" "$(cat "$PLUGIN/skills/orchestrate/SKILL.md")"

echo "== lint: orchestrate-code-reviews =="
ocr="$(cat "$PLUGIN/skills/orchestrate-code-reviews/SKILL.md" 2>/dev/null)"
rb="$(cat "$PLUGIN/references/review-brief.md" 2>/dev/null)"
rs="$(cat "$PLUGIN/references/review-summary.md" 2>/dev/null)"
check "code-reviews: takes the role through the orchestrate skill" "../orchestrate/SKILL.md" "$ocr"
for dep in worktree agent prompt listen; do
    check "code-reviews: points to the $dep skill instead of repeating it" "the \`herdr:$dep\` skill" "$ocr"
done
check "code-reviews: reports in the orchestrator report format" "../../references/report.md" "$ocr"
check "code-reviews: points to the brief reference" "../../references/review-brief.md" "$ocr"
check "code-reviews: points to the summary reference" "../../references/review-summary.md" "$ocr"
check "code-reviews: an empty or placeholder list is asked for first" "placeholders" "$ocr"
check "code-reviews: the reviewer kind question states its default" "state the default" "$ocr"
check "code-reviews: a taken orchestrator name gets a suffix" "orchestrator-pr-review" "$ocr"
check "code-reviews: an existing worktree, workspace or pane is reused" "Reuse what the request names" "$ocr"
check "code-reviews: panes it did not create are left alone" "leave every pane you did not create alone" "$ocr"
check "code-reviews: the workspace label shows number, owner and description" "pr-<number>-<owner>-<short description>" "$ocr"
check "code-reviews: the label is passed, not derived from the branch" "never leave the label to be derived from the branch" "$ocr"
check "code-reviews: a reused workspace is not renamed without asking" "it is not yours to rename" "$ocr"
check "code-reviews: the reviewer's name carries the number and a description" "review-<number>-<short description>" "$ocr"
check "code-reviews: the number survives a cut name" "shorten the description, never the number" "$ocr"
check "code-reviews: the owner's login stays in the label" "it does not go into comments, drafts or summaries" "$ocr"
check "code-reviews: states the map of the group first" "State this map in your first report" "$ocr"
check "code-reviews: a merged pull request gets no worktree" "A merged pull request is reference behaviour only" "$ocr"
check "code-reviews: a merged pull request is never commented on" "never comment on it" "$ocr"
check "code-reviews: a fix for a merged pull request is a proposed follow-up" "proposed follow-up (file, line, change)" "$ocr"
check "code-reviews: reviewers only draft" "Reviewers draft; they post nothing" "$ocr"
check "code-reviews: one poster per pull request" "one agent per pull request" "$ocr"
check "code-reviews: one COMMENT review per pull request" "one \`COMMENT\` review" "$ocr"
check "code-reviews: a finding two agents found is posted once" "is posted once" "$ocr"
check "code-reviews: the rule files are discovered per repository" "Discover each repository's rule files" "$ocr"
check "code-reviews: confirmed facts and leads go into the briefs, labelled" "facts already confirmed" "$ocr"
check "code-reviews: leads are labelled as leads" "leads to verify" "$ocr"
check "code-reviews: the hard rules" "Never mark a pull request ready, approve it, request changes, merge it or push to its branch" "$ocr"
check "code-reviews: never reads secrets" "Never read secrets or credential files" "$ocr"
check "code-reviews: prescribes the summary format" "in the format of \`../../references/review-summary.md\` exactly" "$ocr"
check "code-reviews: ends with cross-PR findings and a merge order" "suggested merge order" "$ocr"
check "code-reviews: the poster re-checks what it posts for another agent" "Re-checks every claim it posts on another agent's behalf" "$ocr"
check "code-reviews: the poster reports its deviations" "It reports each such deviation" "$ocr"
check "code-reviews: replies show as review entries of their own" "the extra entries from replies are expected, not a mistake" "$ocr"
check "code-reviews: the one review is for the new findings" "one review for the **new** inline findings" "$ocr"
check "code-reviews: what was posted is verified through the API" "## 8. Verify what was posted" "$ocr"
check "code-reviews: state and draft flag are checked unchanged" "state and draft flag are what they were at the start" "$ocr"
check "code-reviews: the worktree is checked clean" "the worktree is clean and at the same commit" "$ocr"
check "code-reviews: closes down after posting" "## 9. Close down what you created" "$ocr"
check "code-reviews: the reviewer reports back to a file first" "**Get the reviewer's report back.**" "$ocr"
check "code-reviews: the checkout is checked before removal" "status --porcelain" "$ocr"
check "code-reviews: only what it created is closed" "**Close only what you created for this review:**" "$ocr"
check "code-reviews: removes the worktree through herdr" "herdr worktree remove --workspace" "$ocr"
check "code-reviews: never forces a removal" "never with \`--force\`" "$ocr"
check "code-reviews: a tab in a reused workspace is closed alone" "herdr tab close" "$ocr"
check "code-reviews: reused and unverified things stay open" "**What is never closed here:**" "$ocr"
check "code-reviews: the user can ask to keep the worktrees" "so the user can ask to keep them" "$ocr"
check_absent "code-reviews: never grants repository trust by itself" "remove --trust-repository" "$ocr"
check "code-reviews: the summary becomes the body of the one review" "Put the summary into the body of that same \`COMMENT\` review" "$ocr"
check "code-reviews: the review is submitted with a placeholder body" "a placeholder body" "$ocr"
check "code-reviews: the body is updated in place" "gh api -X PUT repos/<owner>/<repo>/pulls/<number>/reviews/<review id>" "$ocr"
check "code-reviews: the updated body is verified" "the review's body equals the summary file" "$ocr"
check "code-reviews: the review stays a comment" "its state is still \`COMMENTED\`" "$ocr"
check "code-reviews: no findings still gets one review with the summary" "one \`COMMENT\` review whose body is the summary, with no inline comments" "$ocr"
check "code-reviews: filling in its own review body is the one allowed edit" "the one edit that is part of the flow" "$ocr"
check_absent "code-reviews: no separate summary comment" "gh pr comment" "$ocr"
check_absent "code-reviews: no longer a pull request comment" "Always post the summary as a pull request comment" "$ocr"
check_absent "code-reviews: no longer waits to be asked" "only when the user asks" "$ocr"
check "summary: a file first, then always the review's body" "always puts it into the body of the pull request's single \`COMMENT\` review" "$rs"
check_absent "summary: no longer a separate comment" "always posts it as a pull request comment" "$rs"
check_absent "summary: no separate summary comment" "gh pr comment" "$rs"
check "summary: a finding with no inline comment is written out in the summary" "written out in full below the table" "$rs"
check_absent "summary: no longer waits to be asked" "only when the user asks" "$rs"
check "brief: the poster re-checks another agent's items" "Re-check every item that came from another agent's draft" "$rb"
check "brief: carries the hard rules" "Never mark a pull request ready, approve it, request changes, merge it or push to its branch" "$rb"
check "brief: no personal data" "No personal data" "$rb"
check "brief: no AI signature" "No AI signature or attribution lines" "$rb"
check "brief: never reads secrets" "Never read secrets or credential files" "$rb"
check "brief: the proof standard" "## Proof standard" "$rb"
check "brief: the draft format of a finding" "## Draft format" "$rb"
check "brief: a decision is asked for in the agent's own pane" "stop and ask in your own pane" "$rb"
check "brief: temporary test files carry a per-agent prefix" "per-agent prefix" "$rb"
check "brief: temporary test files are never committed" "never commit them and delete them before you finish" "$rb"
check "brief: no installs that change lockfiles" "lockfile" "$rb"
check "brief: a run that did not happen is not claimed" "say so in the draft instead of claiming a run" "$rb"
check "brief: a lead that is not real is reported with its evidence" "report it as not real, with the evidence" "$rb"
check "brief: existing comments are answered only with something to add" "Reply only when there is something to add" "$rb"
check "brief: a stack is reviewed against its own base" "against its own base" "$rb"
check "brief: the fix prompt is self-contained" "self-contained fix prompt" "$rb"
check "summary: the count line by severity" "**<N> findings:**" "$rs"
check "summary: the numbered findings table" "| # | Severity | Finding | Where |" "$rs"
check "summary: findings link to their inline comment" "](<URL of its inline comment>)" "$rs"
check "summary: the unconfirmed section" "Worth a look (not confirmed, not posted inline)" "$rs"
check "summary: the checked section" "Checked and found correct" "$rs"
check "summary: all fix prompts in one block" "Prompt for AI Agents (all findings)" "$rs"
check "summary: says whether tests ran" "whether tests ran" "$rs"
check "summary: the fix prompt names the repository's own rule files" "<the repository's rule files" "$rs"
# Generic: nothing written for one repository or one review product, no real addresses.
for f in skills/orchestrate-code-reviews/SKILL.md references/review-brief.md references/review-summary.md; do
    specific="$(grep -noiE 'coderabbit|luma|docs/testing\.md|config/\*\.json|throwaway|\.npmrc' "$PLUGIN/$f" 2>/dev/null || true)"
    check_rc "$f: nothing specific to one repository or product" 0 "${#specific}"
    [[ -n "$specific" ]] && echo "     $specific"
    real="$(grep -noE 'github\.com/[^< )]+' "$PLUGIN/$f" 2>/dev/null || true)"
    check_rc "$f: only placeholder addresses" 0 "${#real}"
    [[ -n "$real" ]] && echo "     $real"
done
check "readme: lists the review skill" "\`orchestrate-code-reviews\`" "$(cat "$PLUGIN/README.md")"
check "readme: the summary is the review's body" "into the body of that review" "$(cat "$PLUGIN/README.md")"
check_absent "readme: no separate summary comment" "posted as a pull request comment" "$(cat "$PLUGIN/README.md")"

leak="$(grep -rnoiE 'spec-workflow|build-next|implement-task|peer-review|remote-compute|\.neural-network|board\.sh|herdr-graph-engineering' "$PLUGIN" --include='*.md' --include='*.sh' --include='*.json' --exclude-dir=tests || true)"
check_rc "no specialized-plugin knowledge leaks into this plugin" 0 "${#leak}"
[[ -n "$leak" ]] && echo "     $leak"
v1="$(jq -r .version "$PLUGIN/.claude-plugin/plugin.json")"
v2="$(jq -r .version "$PLUGIN/.codex-plugin/plugin.json")"
check "claude and codex manifests carry the same version" "$v1" "$v2"
check "the claude manifest requires herdr" '"herdr"' "$(jq -c .dependencies "$PLUGIN/.claude-plugin/plugin.json")"
